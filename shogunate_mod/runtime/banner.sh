render_ashigaru_ascii() {
    local count="$1"
    local i
    local from=1
    local to=0
    local row1="" row2="" row3="" row4="" row5="" row6="" row7=""
    local per_row=8

    if ! [[ "$count" =~ ^[0-9]+$ ]]; then
        count=1
    fi
    if [ "$count" -lt 1 ]; then
        count=1
    fi
    while [ "$from" -le "$count" ]; do
        to=$((from + per_row - 1))
        if [ "$to" -gt "$count" ]; then
            to="$count"
        fi
        row1="" row2="" row3="" row4="" row5="" row6="" row7=""
        for ((i=from; i<=to; i++)); do
            row1+="       /\\  "
            row2+="      /||\\ "
            row3+="     /_||\\ "
            row4+="       ||  "
            row5+="      /||\\ "
            row6+="      /  \\ "
            row7+="     [足${i}] "
        done
        echo ""
        echo "$row1"
        echo "$row2"
        echo "$row3"
        echo "$row4"
        echo "$row5"
        echo "$row6"
        echo "$row7"
        echo ""
        from=$((to + 1))
    done
}
